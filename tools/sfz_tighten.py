"""Write a "tight" copy of a flat SFZ program: short release, no release-triggered samples.

    python -I tools/sfz_tighten.py SRC.sfz OUT.sfz RELEASE_S [NOTE]

For palm-muted metal parts whose gaps must stay silent after heavy amp gain. Sample paths keep working
because the copy gets a <control> default_path pointing back at the source folder (relative to OUT).
Only for single-file programs (no #include).
"""
import os
import re
import sys

src, out, rel = sys.argv[1], sys.argv[2], float(sys.argv[3])
note = sys.argv[4] if len(sys.argv) > 4 else ""
text = open(src, encoding="utf-8", errors="replace").read()
if "#include" in text or "<control>" in text:
    sys.exit("only flat programs without #include / <control> are supported")
# split into header blocks and drop every <group> (with its regions) that is trigger=release
parts = re.split(r"(?=<group>)", text)
kept = [p for p in parts if not re.search(r"^\s*trigger=release\b", p, re.M)]
body = re.sub(r"ampeg_release=[0-9.]+", f"ampeg_release={rel:g}", "".join(kept))
base = os.path.relpath(os.path.dirname(os.path.abspath(src)), os.path.dirname(os.path.abspath(out))).replace("\\", "/")
head = (f"// Tight copy of {os.path.relpath(src).replace(chr(92), '/')} (generated by tools/sfz_tighten.py)\n"
        f"// release {rel:g} s, release-triggered samples removed. {note}\n<control>\ndefault_path={base}/\n\n")
open(out, "w", encoding="utf-8").write(head + body)
print(f"{out}: {len(parts) - len(kept)} release groups dropped, {body.count('<region>')} regions")
