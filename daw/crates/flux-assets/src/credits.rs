//! License overview (`LICENSES.md`) and the in-game credits text, generated from the manifest, the license
//! audit and the usage scan.

use crate::audit::{Finding, Severity};
use crate::fsutil;
use crate::http::{Expect, HttpClient};
use crate::license::{Family, Scope, Verdict};
use crate::manifest::{Asset, Source};
use crate::usage::Usage;
use crate::verify::short;
use crate::workspace::Workspace;
use anyhow::{Context, Result};
use serde::Serialize;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

/// Whether an asset's credit line must appear in the game.
pub fn credit_required(ws: &Workspace, a: &Asset) -> bool {
    a.credit.as_ref().and_then(|c| c.required).unwrap_or_else(|| ws.loaded.license(a).attribution_required)
}

/// Assets whose credit goes into the game: everything in use that has a credit line, plus required credits of
/// installed assets (usage detection can miss a reference, and an extra credit does no harm).
pub fn credited_assets<'a>(ws: &'a Workspace, usage: Option<&Usage>) -> Vec<&'a Asset> {
    ws.loaded
        .assets()
        .iter()
        .filter(|a| a.scope == Scope::Audio && a.credit.is_some())
        .filter(|a| {
            let used = usage.is_none_or(|u| u.is_used(&a.id));
            used || (credit_required(ws, a) && (a.path.is_none() || ws.is_installed(a)))
        })
        .collect()
}

/// The plain-text credits block for the game (header lines, required credits, then courtesy credits).
pub fn credits_text(ws: &Workspace, usage: Option<&Usage>) -> String {
    let mut out = String::new();
    for l in &ws.loaded.manifest.credits.header {
        out.push_str(l);
        out.push('\n');
    }
    let assets = credited_assets(ws, usage);
    let (req, courtesy): (Vec<&Asset>, Vec<&Asset>) = assets.into_iter().partition(|a| credit_required(ws, a));
    if !out.is_empty() && !(req.is_empty() && courtesy.is_empty()) {
        out.push('\n');
    }
    for c in req.iter().chain(&courtesy).filter_map(|a| a.credit.as_ref()) {
        match &c.role {
            Some(r) => writeln!(out, "{r}: {}", c.text).ok(),
            None => writeln!(out, "{}", c.text).ok(),
        };
    }
    out
}

fn md_escape(s: &str) -> String {
    s.replace('|', "\\|").replace('\n', " ")
}

fn source_cell(a: &Asset) -> String {
    let mut parts = Vec::new();
    for s in &a.sources {
        match s {
            Source::Git(g) => parts.push(format!("{} (commit `{}`)", g.url, short(&g.rev))),
            Source::Archive(x) => parts.push(x.page.clone().unwrap_or_else(|| x.url.clone())),
            Source::Files(f) => parts.push(f.base_url.clone()),
            Source::Manual(m) => parts.push(format!("{} (manual download)", m.page)),
            Source::External(e) => parts.push(e.page.clone()),
            Source::Vendored(v) => parts.push(v.origin.clone().unwrap_or_else(|| "kept in this repository".into())),
        }
    }
    if parts.is_empty() {
        a.homepage.clone().unwrap_or_default()
    } else {
        parts.dedup();
        parts.join("; ")
    }
}

fn license_cell(ws: &Workspace, a: &Asset) -> String {
    let lic = ws.loaded.license(a);
    let names: Vec<String> = lic.parts.iter().map(|p| p.name.clone()).collect();
    let name = if names.is_empty() { a.license.id.clone() } else { names.join(" / ") };
    if matches!(lic.family, Family::PublicDomain | Family::Permissive) { name } else { format!("**{name}**") }
}

fn usage_cell(u: &Usage, a: &Asset) -> String {
    let roots = u.roots_using(&a.id);
    if roots.is_empty() {
        return "not used".into();
    }
    let heuristic = u.uses(&a.id).iter().all(|r| r.heuristic);
    let mut s = roots.iter().map(|r| format!("`{r}`")).collect::<Vec<_>>().join(", ");
    if heuristic {
        s.push_str(" (from script text)");
    }
    s
}

/// Generate the LICENSES.md text.
pub fn licenses_markdown(ws: &Workspace, usage: Option<&Usage>, findings: &[Finding]) -> String {
    let m = &ws.loaded.manifest;
    let mut o = String::new();
    o.push_str("# Licenses & credits\n\n");
    if let Some(intro) = &m.credits.intro {
        o.push_str(intro.trim_end());
        o.push_str("\n\n");
    }
    o.push_str("_Generated by `flux assets licenses` from `assets.toml`; edit the manifest, not this file._\n\n");

    let audio: Vec<&Asset> = ws.loaded.assets().iter().filter(|a| a.scope == Scope::Audio).collect();
    // Who uses what.
    if let Some(u) = usage {
        let mut by_root: std::collections::BTreeMap<&str, Vec<&str>> = Default::default();
        for a in &audio {
            for r in u.roots_using(&a.id) {
                by_root.entry(r).or_default().push(a.name.as_str());
            }
        }
        o.push_str("## What each project uses\n\n");
        if by_root.is_empty() {
            o.push_str("No project references any sound library.\n\n");
        } else {
            o.push_str("| Project file | Sound libraries |\n|---|---|\n");
            for (root, names) in &by_root {
                let _ = writeln!(o, "| `{root}` | {} |", md_escape(&names.join(", ")));
            }
            o.push('\n');
        }
    }

    // Credits.
    o.push_str("## Credits for the game\n\n");
    let credited = credited_assets(ws, usage);
    let required: Vec<&str> = credited.iter().filter(|a| credit_required(ws, a)).map(|a| a.name.as_str()).collect();
    if required.is_empty() {
        o.push_str("No library in use requires a credit. The lines below are courtesy credits.\n\n");
    } else {
        let _ = writeln!(o, "Required by the license: {}. The other lines are courtesy credits.\n", required.join(", "));
    }
    o.push_str("```\n");
    o.push_str(&credits_text(ws, usage));
    o.push_str("```\n\n");

    // Sound content. Without a usage scan (`--no-usage`: a copy that doesn't depend on the local projects) there
    // is no "Used by" column.
    o.push_str("## Sound content (can end up in the game's audio)\n\n");
    if usage.is_some() {
        o.push_str("| Library | Version | License | Credit required? | Used by | Source (official) |\n|---|---|---|---|---|---|\n");
    } else {
        o.push_str("| Library | Version | License | Credit required? | Source (official) |\n|---|---|---|---|---|\n");
    }
    for a in &audio {
        let who = if a.authors.is_empty() { String::new() } else { format!(", by {}", a.authors.join(", ")) };
        let used = usage.map(|u| format!(" {} |", usage_cell(u, a))).unwrap_or_default();
        let _ = writeln!(
            o,
            "| **{}**{} | {} | {} | {} |{used} {} |",
            md_escape(&a.name),
            md_escape(&who),
            md_escape(&a.version),
            license_cell(ws, a),
            if credit_required(ws, a) { "**Yes**" } else { "No" },
            md_escape(&source_cell(a)),
        );
    }
    o.push('\n');
    let noted: Vec<&&Asset> = audio.iter().filter(|a| !a.notes.is_empty() || a.license.note.is_some() || a.license.approved.is_some()).collect();
    if !noted.is_empty() {
        o.push_str("Notes:\n");
        for a in noted {
            if let Some(n) = &a.license.note {
                let _ = writeln!(o, "- **{}**: {}", a.name, n.trim());
            }
            if let Some(ap) = &a.license.approved {
                let _ = writeln!(o, "- **{}**: owner approval: {}", a.name, ap.trim());
            }
            for n in &a.notes {
                let _ = writeln!(o, "- **{}**: {}", a.name, n.trim());
            }
        }
        o.push('\n');
    }

    // Flags.
    let flagged: Vec<&Finding> = findings.iter().filter(|f| f.severity >= Severity::Warning).collect();
    o.push_str("## Open license questions\n\n");
    if flagged.is_empty() {
        o.push_str("None: every asset's license allows commercial use in the game and its text was found.\n\n");
    } else {
        for f in flagged {
            let name = ws.loaded.asset(&f.asset).map_or(f.asset.as_str(), |a| a.name.as_str());
            let _ = writeln!(o, "- **{}** ({}, `{}`): {}", name, f.severity.as_str(), f.code, f.message);
        }
        o.push('\n');
    }

    // Tools.
    let tools: Vec<&Asset> = ws.loaded.assets().iter().filter(|a| a.scope == Scope::Tool).collect();
    if !tools.is_empty() {
        o.push_str("## Tools (not shipped in the game; their licenses don't attach to rendered audio)\n\n");
        o.push_str("| Tool | Version | License | Source |\n|---|---|---|---|\n");
        for a in tools {
            let _ = writeln!(o, "| {} | {} | {} | {} |", md_escape(&a.name), md_escape(&a.version), license_cell(ws, a), md_escape(&source_cell(a)));
        }
        o.push('\n');
    }
    let app: Vec<&Asset> = ws.loaded.assets().iter().filter(|a| a.scope == Scope::App).collect();
    if !app.is_empty() {
        o.push_str("## Bundled with Flux (the DAW; nothing from it ships in the game)\n\n");
        o.push_str("| Asset | Version | License | Source |\n|---|---|---|---|\n");
        for a in app {
            let _ = writeln!(o, "| {} | {} | {} | {} |", md_escape(&a.name), md_escape(&a.version), license_cell(ws, a), md_escape(&source_cell(a)));
        }
        o.push('\n');
    }

    // License texts.
    o.push_str("## Where the license texts are\n\n");
    for a in ws.loaded.assets() {
        let loc = match (&a.license.file, &a.path, &a.license.text_url) {
            (Some(f), Some(p), _) => {
                let sec = a.license.section.as_ref().map(|s| format!(" (section \"{s}\")")).unwrap_or_default();
                format!("`{p}/{f}`{sec}")
            }
            (_, _, Some(u)) => u.clone(),
            _ => "**not recorded**".into(),
        };
        let _ = writeln!(o, "- {}: {} ({})", a.name, loc, a.license.id);
    }
    o
}

/// Audio assets that are installed or used but not mentioned in an existing LICENSES.md.
pub fn missing_from(ws: &Workspace, existing: &str, usage: Option<&Usage>) -> Vec<String> {
    let text = existing.to_lowercase();
    ws.loaded
        .assets()
        .iter()
        .filter(|a| a.scope == Scope::Audio)
        .filter(|a| usage.is_some_and(|u| u.is_used(&a.id)) || ws.is_installed(a))
        .filter(|a| !text.contains(&a.name.to_lowercase()) && !text.contains(&a.id.to_lowercase()))
        .map(|a| a.id.clone())
        .collect()
}

/// One collected license text.
#[derive(Clone, Debug, Serialize)]
pub struct CollectedText {
    pub asset: String,
    /// Where it was written, relative to the output folder.
    pub file: String,
    /// `install` (copied from the asset folder) or `url` (downloaded).
    pub origin: String,
    pub sha256: String,
    /// Set when a pinned `text_sha256` exists and matched.
    pub pinned: bool,
}

/// Copy every asset's license text into `dest/<id>/`: from the install when it has one, otherwise downloaded
/// from `license.text_url` (checked against `text_sha256` when pinned). Failures are listed, not fatal.
pub fn collect_texts(ws: &Workspace, dest: &Path) -> Result<(Vec<CollectedText>, Vec<String>)> {
    fs::create_dir_all(dest).with_context(|| format!("creating {}", dest.display()))?;
    let http = HttpClient::new(ws.http.clone())?;
    let mut done = Vec::new();
    let mut failed = Vec::new();
    for a in ws.loaded.assets() {
        let dir = dest.join(&a.id);
        if let (Some(f), Some(root)) = (&a.license.file, ws.asset_dir(a))
            && ws.is_installed(a)
        {
            let src = root.join(f);
            match fs::read(&src) {
                Ok(bytes) => {
                    let name = Path::new(f).file_name().map_or("LICENSE".into(), |n| n.to_string_lossy().into_owned());
                    fs::create_dir_all(&dir).with_context(|| format!("creating {}", dir.display()))?;
                    fsutil::atomic_write(&dir.join(&name), &bytes)?;
                    done.push(CollectedText {
                        asset: a.id.clone(),
                        file: format!("{}/{name}", a.id),
                        origin: "install".into(),
                        sha256: crate::hash::sha256_bytes(&bytes),
                        pinned: false,
                    });
                    continue;
                }
                Err(e) => failed.push(format!("{}: {}: {e}", a.id, src.display())),
            }
        }
        if let Some(url) = &a.license.text_url {
            let name = crate::workspace::file_name_from_url(url).unwrap_or_else(|| "LICENSE.html".into());
            let to = dir.join(&name);
            let expect = Expect { sha256: a.license.text_sha256.clone(), size: None, max_bytes: 4 << 20, allow_html: true };
            match http.download(url, &to, &expect, &mut |_, _| {}) {
                Ok(d) => done.push(CollectedText {
                    asset: a.id.clone(),
                    file: format!("{}/{name}", a.id),
                    origin: "url".into(),
                    sha256: d.sha256,
                    pinned: a.license.text_sha256.is_some(),
                }),
                Err(e) => failed.push(format!("{}: {url}: {e:#}", a.id)),
            }
        } else if a.license.file.is_none() && !matches!(ws.loaded.license(a).family, Family::Proprietary) {
            failed.push(format!("{}: no license file or text_url recorded", a.id));
        }
    }
    Ok((done, failed))
}

/// One line per asset for `status`: verdict and whether a credit is needed.
pub fn verdict_label(v: Verdict) -> &'static str {
    match v {
        Verdict::Allowed => "ok",
        Verdict::AllowedWithCredit => "ok, credit",
        Verdict::Approved => "approved",
        Verdict::NeedsApproval => "NEEDS APPROVAL",
        Verdict::Blocked => "BLOCKED",
    }
}
